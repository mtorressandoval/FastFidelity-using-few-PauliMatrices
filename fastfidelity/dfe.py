class LocalStats:
    """Outcome counts and sums of all substrings of weight <= k of the measured
    strings, kept in sorted arrays and updated in chunks (any n <= 31)."""

    def __init__(self, n, k, chunk=4000, max_keys=15_000_000, min_count=3):
        import itertools
        self.n, self.k, self.chunk = n, k, chunk
        self.max_keys, self.min_count = max_keys, min_count     # memory bound
        self.keys = np.zeros(0, dtype=np.int64)
        self.cnt = np.zeros(0, dtype=np.int64)
        self.sm = np.zeros(0, dtype=np.int64)
        self._buf_k, self._buf_o, self._nbuf = [], [], 0
        self._combos = {}
        self._it = itertools

    def _index(self, w):
        hit = self._combos.get(w)
        if hit is None:
            rows = [c + (-1,) * (self.k - len(c)) for j in range(1, min(self.k, w) + 1)
                    for c in self._it.combinations(range(w), j)]
            hit = np.array(rows, dtype=np.int64).reshape(-1, self.k) if rows else np.zeros((0, self.k), np.int64)
            self._combos[w] = hit
        return hit

    def add(self, keys, bits):
        n = self.n
        keys = np.asarray(keys).astype(np.int64)
        bits = np.asarray(bits).astype(np.int64)
        uniq, inv = np.unique(keys, return_inverse=True)
        for u, P in enumerate(uniq.tolist()):
            x, z = pl.split(P, n)
            pos = np.array([j for j in range(n) if ((x | z) >> j) & 1], dtype=np.int64)
            idx = self._index(len(pos))
            if idx.size == 0:
                continue
            pw = np.where(idx >= 0, np.left_shift(np.int64(1), pos[np.maximum(idx, 0)]), 0)
            mask = np.bitwise_or.reduce(pw, axis=1)
            sk = ((x & mask) << n) | (z & mask)
            b = bits[inv == u]
            o = 1 - 2 * (pl.popcount(b[:, None] & mask[None, :]) & 1)
            self._buf_k.append(sk)
            self._buf_o.append((o.sum(axis=0), np.full(sk.shape, b.shape[0])))
            self._nbuf += b.shape[0]
        if self._nbuf >= self.chunk:
            self.flush()

    def flush(self):
        if not self._buf_k:
            return
        k = np.concatenate([self.keys] + self._buf_k)
        s = np.concatenate([self.sm] + [a for a, _ in self._buf_o])
        c = np.concatenate([self.cnt] + [b for _, b in self._buf_o])
        u, inv = np.unique(k, return_inverse=True)
        self.keys, self.sm = u, np.bincount(inv, weights=s, minlength=u.size).astype(np.int64)
        self.cnt = np.bincount(inv, weights=c, minlength=u.size).astype(np.int64)
        self._buf_k, self._buf_o, self._nbuf = [], [], 0
        if self.keys.size > self.max_keys:
            # strings with fewer than min_count outcomes cannot pass the acceptance
            # threshold |o| - 3/sqrt(m) > 0.2 (which needs m >= 15), so they are dropped
            keep = self.cnt >= self.min_count
            self.keys, self.cnt, self.sm = self.keys[keep], self.cnt[keep], self.sm[keep]

    def table(self):
        self.flush()
        return self.keys, self.cnt, self.sm


class _PauliData:
    """Outcome counts and sums per unsigned Pauli string (direct or substrings)."""

    def __init__(self, n, substrings=False, dense_max=12, max_sub_weight=None, local_k=None):
        self.n = n
        self.local = LocalStats(n, local_k) if (local_k and n > dense_max) else None
        self.local_k = local_k
        self.substrings = substrings
        self.dense = n <= dense_max
        self.max_sub_weight = n if max_sub_weight is None else max_sub_weight
        if self.dense:
            self.cnt = np.zeros(1 << (2 * n), dtype=np.int64)
            self.sm = np.zeros(1 << (2 * n), dtype=np.int64)
        else:
            self.cnt_d, self.sm_d = {}, {}
        self._sub_tables = {}
        self.total_shots = 0

    def _subtable(self, P):
        """All substrings of P (keys) and their support masks."""
        hit = self._sub_tables.get(P)
        if hit is not None:
            return hit
        n = self.n
        x, z = pl.split(P, n)
        pos = [j for j in range(n) if ((x | z) >> j) & 1]
        w = len(pos)
        A = np.arange(1 << w, dtype=np.int64)
        mask = np.zeros(1 << w, dtype=np.int64)
        for t, j in enumerate(pos):
            mask |= ((A >> t) & 1) << j
        if self.max_sub_weight < w:
            keep = pl.popcount(mask) <= self.max_sub_weight
            keep[-1] = True
            mask = mask[keep]
        keys = ((x & mask) << n) | (z & mask)
        out = (keys, mask)
        if w <= 12:                                # bounded memory for large n
            if len(self._sub_tables) >= 4000:
                self._sub_tables.pop(next(iter(self._sub_tables)))
            self._sub_tables[P] = out
        return out

    def local_table(self, k):
        """(keys, counts, sums) of the stored strings of weight 1..k."""
        if self.dense and self.substrings:
            ks = np.nonzero(self.cnt)[0].astype(np.int64)
            ks = ks[(pl.weight(ks, self.n) <= k) & (ks != 0)]
            return ks, self.cnt[ks], self.sm[ks]
        if self.local is not None:
            return self.local.table()
        return np.zeros(0, np.int64), np.zeros(0, np.int64), np.zeros(0, np.int64)

    def add(self, keys, bits):
        n = self.n
        self.total_shots += len(keys)
        if self.local is not None:
            self.local.add(keys, bits)
        if not self.substrings:
            o = outcomes_from_bits(bits, keys, n)
            if self.dense:
                np.add.at(self.cnt, keys.astype(np.int64), 1)
                np.add.at(self.sm, keys.astype(np.int64), o)
            else:
                for k, oo in zip(keys, o):
                    k = int(k)
                    self.cnt_d[k] = self.cnt_d.get(k, 0) + 1
                    self.sm_d[k] = self.sm_d.get(k, 0) + int(oo)
            return
        uniq, inv = np.unique(np.asarray(keys), return_inverse=True)
        for t, P in enumerate(uniq):
            b = np.asarray(bits)[inv == t].astype(np.int64)
            sk, mask = self._subtable(int(P))
            o = 1 - 2 * (pl.popcount(b[:, None] & mask[None, :]) & 1)
            ssum = o.sum(axis=0)
            if self.dense:
                self.cnt[sk] += b.shape[0]
                self.sm[sk] += ssum
            else:
                for k, v in zip(sk, ssum):
                    k = int(k)
                    self.cnt_d[k] = self.cnt_d.get(k, 0) + b.shape[0]
                    self.sm_d[k] = self.sm_d.get(k, 0) + int(v)

    def stored_keys(self):
        """Unsigned keys with at least one outcome (direct or as substring)."""
        if self.dense:
            return np.nonzero(self.cnt)[0].astype(np.int64)
        ks = list(self.cnt_d.keys())
        return np.array(ks, dtype=np.int64 if self.n <= 31 else object)

    def get(self, keys):
        if self.dense:
            kk = np.asarray(keys).astype(np.int64)
            return self.cnt[kk], self.sm[kk]
        c = np.array([self.cnt_d.get(int(k), 0) for k in keys], dtype=np.int64)
        s = np.array([self.sm_d.get(int(k), 0) for k in keys], dtype=np.int64)
        return c, s


class _StoreBase:
    """Common machinery: data, locations, completion of shots, estimator."""

    def __init__(self, backend, rng, substrings=False, dense_max=12, max_sub_weight=None, local_k=None):
        self.backend, self.rng = backend, rng
        self.n = backend.n
        self.data = _PauliData(self.n, substrings and self.n <= dense_max, dense_max, max_sub_weight,
                               local_k if substrings else None)
        self.substrings = substrings
        self.loc_keys = []          # key of every location ever drawn
        self.shots = 0
        self.requested = 0
        self.n_locations = 0
        self.n_reused = 0

    # ---------------------------------------------------------------- shots
    def _measure(self, keys):
        keys = np.asarray(keys)
        if keys.size == 0:
            return
        bits = self.backend.measure(keys, self.rng)
        self.data.add(keys, bits)
        self.shots += int(keys.size)

    def _complete(self, loc_keys):
        """Measure each location Q until it has at least as many data as uses."""
        uq, cq = np.unique(np.asarray(loc_keys), return_counts=True)
        have, _ = self.data.get(uq)
        need = np.maximum(cq - have, 0)
        if need.sum():
            self._measure(np.repeat(uq, need))
        return int(need.sum()), int(np.sum(np.minimum(cq, have)))

    @property
    def reuse_rate(self):
        """Fraction of the requested shots that were served from the store."""
        return 1.0 - self.shots / self.requested if self.requested else 0.0


class StoreDFE(_StoreBase):
    """DFE with a Pauli store and a stratified estimator.

    The group U of the target is split into two strata:

    * K = Paulis of U that already have data in the store.  This stratum is
      evaluated deterministically, i.e. every P in K enters with its weight
      1/|U| and the mean of all its stored outcomes.  Before that, every P in
      K is topped up to at least ceil(N/|U|) outcomes, so that this stratum is
      never noisier than its share of a fresh DFE.
    * R = U \\ K.  This stratum is sampled: ceil(N |R|/|U|) Paulis are drawn
      uniformly from R (rejection sampling from U) and measured once each.

    The estimator  A = (1/|U|) sum_{P in K} s_P obar_P + (|R|/|U|) mean_R(s o)
    is unbiased for any sequence of queries fixed in advance, and its variance
    does not exceed that of a fresh DFE with N shots.  With an empty store it
    reduces to FreshDFE and consumes the same random numbers.
    """

    def _known(self, T, m):
        if self.data.dense and m <= 16:
            # enumerate the (sub)group and look up which strings have data:
            # 2^m operations instead of a scan over every stored string
            k, _ = T.element(np.arange(1 << m, dtype=np.int64))
            k = np.asarray(k, dtype=np.int64)
            return np.sort(k[self.data.cnt[k] > 0])
        ks = self.data.stored_keys()
        if ks.size == 0:
            return ks
        inside = T.in_group(ks)
        if m < T.n and inside.any():
            u = T.coords(ks[inside])
            sel = np.nonzero(inside)[0][np.asarray((u >> m) == 0, dtype=bool)]
            inside = np.zeros(ks.shape, bool)
            inside[sel] = True
        return ks[inside]

    def estimate(self, T, N, m=None):
        n = self.n
        m = n if m is None else m
        size = float(2 ** m)
        K = self._known(T, m)
        nK = int(K.size)
        new = 0
        # deterministic stratum: top up to ceil(N/|U|) outcomes per Pauli
        if nK:
            r = math.ceil(N / size)
            cnt, _ = self.data.get(K)
            need = np.maximum(r - cnt, 0)
            if need.sum():
                self._measure(np.repeat(K, need))
                new += int(need.sum())
            cnt, sm = self.data.get(K)
            sK = T.sign_of(K)
            obar = sm / cnt
            valK = sK * obar
            varK = float(np.sum((1 - obar ** 2) / cnt)) / size ** 2
        else:
            valK, varK = np.zeros(0), 0.0
            K = np.zeros(0, dtype=np.int64 if n <= 31 else object)
        wR = 1.0 - nK / size
        NR = math.ceil(N * wR - 1e-9) if nK < size else 0
        # sampled stratum (rejection from U; identical to FreshDFE if K is empty)
        if NR:
            kset = set(K.tolist())
            keys, signs, us = [], [], []
            todo = NR
            while todo:
                k, s, u = T.sample(self.rng, todo, m)
                ok = np.array([int(t) not in kset for t in k.tolist()], dtype=bool) if nK else np.ones(todo, bool)
                keys.append(k[ok]); signs.append(s[ok]); us.append(u[ok])
                todo -= int(ok.sum())
            kR, sR, uR = np.concatenate(keys), np.concatenate(signs), np.concatenate(us)
            bits = self.backend.measure(kR, self.rng)
            vR = (sR * outcomes_from_bits(bits, kR, n)).astype(float)
            self.data.add(kR, bits)
            self.shots += NR
            new += NR
            varR = (np.var(vR, ddof=1) if NR > 1 else 1.0) * wR ** 2 / NR
        else:
            kR, uR, vR, varR = K[:0], np.zeros(0, dtype=np.int64 if m <= 62 else object), np.zeros(0), 0.0
        value = float(np.sum(valK) / size + (wR * vR.mean() if NR else 0.0))
        uK = T.coords(K) if nK else np.zeros(0, dtype=np.int64)
        udt = np.int64 if m <= 62 else object
        u = np.concatenate([np.asarray(uK, dtype=udt), np.asarray(uR, dtype=udt)])
        coef = np.concatenate([np.full(nK, 1.0 / size), np.full(NR, wR / NR if NR else 0.0)])
        val = np.concatenate([np.asarray(valK, float), vR])
        self.requested += N
        self.n_locations += nK + NR
        self.n_reused += nK
        return Estimate(value, float(np.sqrt(varK + varR)), new, u, coef, val,
                        reused=nK, strata=2, m=m)


def make_estimator(kind, backend, rng, substrings=False, **kw):
    """kind: None/'fresh' (DFE without store) or 'store' (DFE with store)."""
    if kind in (None, False, "fresh", "none"):
        return FreshDFE(backend, rng)
    if kind in (True, "store", "exact", "affine"):
        return StoreDFE(backend, rng, substrings, **kw)
    raise ValueError(kind)
