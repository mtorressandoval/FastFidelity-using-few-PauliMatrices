"""Direct fidelity estimation (DFE) for stabilizer targets, with and without store.

All estimators share the interface

    est = estimator.estimate(T, N, m=None)

which estimates  A = E_u[ s_u tr(rho W_{g_u}) ]  with u uniform over the group
of the stabilizer tableau ``T`` (or over the subgroup generated by its first m
generators).  For m = n, A = f(T) = <z|rho|z>.  The returned ``Estimate``
also keeps every location u with its weight and value, so that all p_x follow
from the same data by a Walsh transform (``Estimate.walsh``).

FreshDFE   DFE without store: every call measures N new uniformly drawn Paulis
           of the group, one shot each.  For stabilizer targets this is the DFE
           of Flammia and Liu (and of ``Mean_Direct_Fidelity`` in the legacy
           folder), since chi_P^2 = 2^-n is uniform on the group.
StoreDFE   DFE with store and stratified estimator: deterministic stratum from
           the store plus a sampled stratum for the rest of the group.

StoreDFE accepts ``substrings=True``: every shot of a string P then also feeds
all its substrings Q <= P (parity of the outcome bits on supp Q).
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field

import numpy as np

from . import paulis as pl
from .backends import outcomes_from_bits
from .walsh import fwht

__all__ = ["Estimate", "FreshDFE", "StoreDFE", "make_estimator"]


@dataclass
class Estimate:
    value: float
    stderr: float
    new_shots: int
    u: np.ndarray
    coef: np.ndarray
    val: np.ndarray
    reused: int = 0
    strata: int = 1
    m: int = 0

    @property
    def n_loc(self):
        return int(self.u.shape[0])

    def walsh(self):
        """p_hat_x for all x in F_2^m (exact Walsh transform, m <= ~22)."""
        h = np.zeros(1 << self.m)
        np.add.at(h, self.u.astype(np.int64), self.coef * self.val)
        return fwht(h)

    def character(self, alphas):
        """sum_loc coef*val*(-1)^{alpha.u} for a list/array of alphas."""
        w = self.coef * self.val
        if self.m <= 62:
            alphas = np.asarray(alphas, dtype=np.int64)
            par = pl.popcount(alphas[:, None] & self.u.astype(np.int64)[None, :]) & 1
            return ((1 - 2 * par) * w[None, :]).sum(axis=1)
        us = [int(t) for t in self.u]
        return np.array([sum(wi * (1 - 2 * ((int(a) & ui).bit_count() & 1)) for wi, ui in zip(w, us))
                         for a in alphas])


class FreshDFE:
    """DFE without store: N new uniformly drawn group elements, one shot each."""

    def __init__(self, backend, rng):
        self.backend, self.rng = backend, rng
        self.n = backend.n
        self.shots = 0
        self.requested = 0

    def estimate(self, T, N, m=None):
        m = T.n if m is None else m
        k, s, u = T.sample(self.rng, N, m)
        bits = self.backend.measure(k, self.rng)
        v = s * outcomes_from_bits(bits, k, self.n)
        self.shots += N
        self.requested += N
        se = float(np.std(v, ddof=1) / np.sqrt(N)) if N > 1 else 1.0
        return Estimate(float(v.mean()), se, N, u, np.full(N, 1.0 / N), v.astype(float),
                        reused=0, strata=1, m=m)

    @property
    def reuse_rate(self):
        return 0.0


